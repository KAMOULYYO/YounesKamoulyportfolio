const frToEn = new Map();
const enToFr = new Map();

translationPairs.forEach(([fr, en]) => {
  frToEn.set(fr, en);
  enToFr.set(en, fr);
});

function translateString(value, language) {
  if (typeof value !== 'string') return value;
  if (language === 'fr') return enToFr.get(value) || value;
  if (language === 'en') return frToEn.get(value) || value;
  return value;
}

function deepTranslate(value, language) {
  if (Array.isArray(value)) {
    return value.map((item) => deepTranslate(item, language));
  }

  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [key, deepTranslate(item, language)])
    );
  }

  return translateString(value, language);
}

export function localizeConfig(config, language) {
  if (!config) return config;

  return {
    ...config,
    meta: deepTranslate(config.meta, language),
    sections: (config.sections || []).map((section) => ({
      ...section,
      name: translateString(section.name, language),
      data: deepTranslate(section.data, language),
    })),
  };
}

